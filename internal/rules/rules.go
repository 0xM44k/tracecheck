// Package rules turns canary fixes into configuration you can review and apply.
// tracecheck never applies configuration itself.
package rules

import (
	"fmt"
	"sort"
	"strings"

	"github.com/0xM44k/tracecheck/internal/canary"
)

type item struct {
	line  string
	ids   []string
	techs []string
	notes []string
}

func collect(cs []canary.Canary, want map[string]bool, pick func(canary.Fix) []string) []*item {
	var order []*item
	idx := map[string]*item{}
	for _, c := range cs {
		if want != nil && !want[c.ID] {
			continue
		}
		lines := pick(c.Fix)
		if len(lines) == 0 && c.Fix.Note == "" {
			continue
		}
		if len(lines) == 0 { // a note with no command: keep it visible
			it := &item{ids: []string{c.ID}, techs: []string{c.Technique}, notes: []string{c.Fix.Note}}
			order = append(order, it)
			continue
		}
		for _, l := range lines {
			it, ok := idx[l]
			if !ok {
				it = &item{line: l}
				idx[l] = it
				order = append(order, it)
			}
			it.ids = append(it.ids, c.ID)
			it.techs = append(it.techs, c.Technique)
			if c.Fix.Note != "" {
				dup := false
				for _, n := range it.notes {
					dup = dup || n == c.Fix.Note
				}
				if !dup {
					it.notes = append(it.notes, c.Fix.Note)
				}
			}
		}
	}
	return order
}

// Generate returns auditd rules (linux) or a command list (windows) for the
// canaries whose IDs are in want. A nil want means all of them. A rule that
// serves several checks is written once, with all of them named above it.
func Generate(goos, version string, cs []canary.Canary, want map[string]bool) string {
	var b strings.Builder
	switch goos {
	case "linux":
		fmt.Fprintf(&b, "## Generated by tracecheck %s. Review before loading: execve and connect rules are noisy.\n", version)
		b.WriteString("## Save as /etc/audit/rules.d/tracecheck.rules, then run: augenrules --load\n")
		b.WriteString("## Test a file without installing it: auditctl -R FILE\n-b 8192\n")
		for _, it := range collect(cs, want, func(f canary.Fix) []string { return f.Auditd }) {
			fmt.Fprintf(&b, "\n## %s\n", strings.Join(it.ids, ", ")+" ("+strings.Join(uniq(it.techs), ", ")+")")
			for _, n := range it.notes {
				fmt.Fprintf(&b, "## %s\n", n)
			}
			if it.line != "" {
				b.WriteString(it.line + "\n")
			}
		}
	case "windows":
		fmt.Fprintf(&b, "REM Generated by tracecheck %s. Review, then run from an elevated prompt.\r\n", version)
		for _, it := range collect(cs, want, func(f canary.Fix) []string { return f.Windows }) {
			fmt.Fprintf(&b, "\r\nREM %s\r\n", strings.Join(it.ids, ", ")+" ("+strings.Join(uniq(it.techs), ", ")+")")
			for _, n := range it.notes {
				fmt.Fprintf(&b, "REM %s\r\n", n)
			}
			if it.line != "" {
				b.WriteString(it.line + "\r\n")
			}
		}
	}
	return b.String()
}

func uniq(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

// IDs returns the sorted IDs in a set.
func IDs(m map[string]bool) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
