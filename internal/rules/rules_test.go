func cx(id, tech string, auditd, win []string, note string) canary.Canary {
	return canary.Canary{ID: id, Technique: tech, Fix: canary.Fix{Auditd: auditd, Windows: win, Note: note}}
}

func TestGenerate_Linux_DedupesSharedRule(t *testing.T) {
	rule := `-a always,exit -F arch=b64 -S execve,execveat -F key=tracecheck_exec`
	cs := []canary.Canary{
		cx("lin-exec-shell", "T1059.004", []string{rule}, nil, ""),
		cx("lin-discovery-uname", "T1082", []string{rule}, nil, ""),
	}
	out := Generate("linux", "0.1.0", cs, nil)
	if strings.Count(out, rule) != 1 {
		t.Fatalf("expected the shared rule to appear exactly once, got %d times:\n%s", strings.Count(out, rule), out)
	}
	if !strings.Contains(out, "lin-exec-shell, lin-discovery-uname") {
		t.Errorf("expected the comment to list both IDs, got:\n%s", out)
	}
	if !strings.Contains(out, "(T1059.004, T1082)") {
		t.Errorf("expected both techniques listed, got:\n%s", out)
	}
	if !strings.Contains(out, "-b 8192") {
		t.Error("expected the backlog header line")
	}
}

func TestGenerate_Linux_WantFilter(t *testing.T) {
	cs := []canary.Canary{
		cx("a", "T1", []string{"-w /etc/shadow -p r -k k1"}, nil, ""),
		cx("b", "T2", []string{"-w /etc/passwd -p w -k k2"}, nil, ""),
	}
	out := Generate("linux", "0.1.0", cs, map[string]bool{"a": true})
	if !strings.Contains(out, "/etc/shadow") {
		t.Error("expected rule for wanted canary a")
	}
	if strings.Contains(out, "/etc/passwd") {
		t.Error("did not expect rule for unwanted canary b")
	}
}

func TestGenerate_Linux_NoteOnlyCanaryStaysVisible(t *testing.T) {
	cs := []canary.Canary{
		cx("note-only", "T9999", nil, nil, "no auditd rule covers this; rely on EDR"),
	}
	out := Generate("linux", "0.1.0", cs, nil)
	if !strings.Contains(out, "no auditd rule covers this; rely on EDR") {
		t.Errorf("expected the note to appear even with no rule line, got:\n%s", out)
	}
}

func TestGenerate_Linux_DuplicateNotesNotRepeated(t *testing.T) {
	rule := "-w /etc/cron.d -p wa -k tracecheck_cron"
	cs := []canary.Canary{
		cx("a", "T1", []string{rule}, nil, "shared note"),
		cx("b", "T2", []string{rule}, nil, "shared note"),
	}
	out := Generate("linux", "0.1.0", cs, nil)
	if strings.Count(out, "shared note") != 1 {
		t.Errorf("expected duplicate identical note to be collapsed, got %d times:\n%s", strings.Count(out, "shared note"), out)
	}
}

func TestGenerate_Windows_UsesCRLF(t *testing.T) {
	cs := []canary.Canary{
		cx("win-exec-cmd", "T1059.003", nil, []string{"auditpol /set /subcategory:\"Process Creation\" /success:enable"}, ""),
	}
	out := Generate("windows", "0.1.0", cs, nil)
	if !strings.Contains(out, "\r\n") {
		t.Error("expected CRLF line endings for Windows output")
	}
	if !strings.HasPrefix(out, "REM Generated by tracecheck 0.1.0") {
		t.Errorf("unexpected header: %q", out[:min(60, len(out))])
	}
}

func TestGenerate_EmptyCanaryListProducesHeaderOnly(t *testing.T) {
	out := Generate("linux", "0.1.0", nil, nil)
	if !strings.Contains(out, "Generated by tracecheck") {
		t.Error("expected header even with no canaries")
	}
}

func TestUniq(t *testing.T) {
	got := uniq([]string{"a", "b", "a", "c", "b"})
	want := []string{"a", "b", "c"}
	if len(got) != len(want) {
		t.Fatalf("got %v", got)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("index %d: got %q want %q", i, got[i], want[i])
		}
	}
}

func TestIDs_Sorted(t *testing.T) {
	m := map[string]bool{"z": true, "a": true, "m": true}
	got := IDs(m)
	want := []string{"a", "m", "z"}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("index %d: got %q want %q", i, got[i], want[i])
		}
	}
}

func min(a, b int) int {
	if a < b {
		return a
	}
	return b
}
